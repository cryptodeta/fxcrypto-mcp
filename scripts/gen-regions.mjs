// Regenerates packages/core/src/data/regions.ts from Unicode CLDR (cldr-core, Unicode-3.0 licence).
// Usage: node scripts/gen-regions.mjs
import { writeFileSync } from "node:fs";

const url = "https://cdn.jsdelivr.net/npm/cldr-core/supplemental/currencyData.json";
const res = await fetch(url);
if (!res.ok) throw new Error(`Failed to download CLDR currency data: HTTP ${res.status}`);
const data = (await res.json()).supplemental.currencyData;

const regions = {};
for (const [region, entries] of Object.entries(data.region)) {
  if (!/^[A-Z]{2}$/.test(region)) continue;
  const current = [];
  for (const entry of entries) {
    for (const [code, info] of Object.entries(entry)) {
      if (!info._to && info._tender !== "false") current.push(code);
    }
  }
  if (current.length) regions[region] = current;
}
const digits = {};
for (const [code, info] of Object.entries(data.fractions)) {
  if (code !== "DEFAULT" && info._digits !== "2") digits[code] = Number(info._digits);
}

const body = `// Generated by scripts/gen-regions.mjs from Unicode CLDR currencyData. Do not edit by hand.
/** ISO 3166-1 region code -> currencies currently in legal tender (primary first). */
export const REGION_CURRENCIES: Record<string, string[]> = ${JSON.stringify(regions)};
/** Minor-unit digits for currencies that do not use 2 decimals. */
export const CURRENCY_DIGITS: Record<string, number> = ${JSON.stringify(digits)};
`;
writeFileSync(new URL("../packages/core/src/data/regions.ts", import.meta.url), body);
console.log(`Wrote ${Object.keys(regions).length} regions`);
